#!/usr/bin/env python3
"""
metro_layout.py — lay out a metro-map skill tree from TREE/skills.yml.

Usage:
    python3 _scripts/metro_layout.py play/supercon26

skills.yml is the file you edit: topics in order, each with a title, a color
and its skills in order. Each topic becomes one line on the map and its skills
become stations, in the order listed. A line branches off the station its
first skill needs (the first id in that skill's `needs`). The one skill with
no needs is the start. Needs you don't pass on the way to a station (riding
from the start) are listed for it as "also needs".

The layout is written into TREE/index.md's front matter, between the "Metro
layout" and "end of metro layout" comment lines (added at the end of the front
matter if they aren't there yet). Don't edit that block: change skills.yml and
rerun this script.

It also writes TREE/metro-map.svg: the same map as a standalone image (styles
inline, legend underneath, nothing interactive) for slides and print, and
renders it to TREE/metro-map.png at 2× size if Inkscape is installed.

Layout rules: the start line runs along the top. Every other line gets a row
of its own below the line it branches from: it drops straight down from its
branch station, then turns right. Rows are filled depth-first, and branches
that leave from further right are placed first (nearest), so a line never
runs through a station.
"""
import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path
from xml.sax.saxutils import escape

import yaml

COL = 130          # px between stations
ROW = 85           # px between lines
DIAG = 45          # size of the 45° turn from a drop into its row
OFFSET = 9         # px between lines that drop from the same station
WRAP = 16          # label characters per line
LEFT, TOP, RIGHT, BOTTOM = 130, 70, 90, 40
PNG_SCALE = 2      # metro-map.png is this many times the SVG's size

BLOCK_START = "# ── Metro layout (generated by _scripts/metro_layout.py from skills.yml) ──"
BLOCK_NOTE = "# Don't edit: change skills.yml and rerun the script."
BLOCK_END = "# ── end of metro layout ──"
FRONT_MATTER = re.compile(r"\A---\s*\n(.*?\n)---\s*\n", re.S)


def fail(msg):
    sys.exit(f"error: {msg}")


def warn(msg):
    print(f"warning: {msg}", file=sys.stderr)


def wrap(text, width=WRAP):
    lines, line = [], ""
    for word in text.split():
        if line and len(line) + 1 + len(word) > width:
            lines.append(line)
            line = word
        else:
            line = f"{line} {word}" if line else word
    return lines + [line] if line else lines


def load(tree):
    data = yaml.safe_load((tree / "skills.yml").read_text())
    topics = data.get("topics") or fail("skills.yml has no topics")
    skills = {}
    for t in topics:
        if not t.get("skills"):
            fail(f"topic {t.get('id')} has no skills")
        for i, s in enumerate(t["skills"]):
            if s["id"] in skills:
                fail(f"skill {s['id']} is listed twice")
            skills[s["id"]] = dict(s, topic=t["id"], index=i, needs=s.get("needs") or [])
    for s in skills.values():
        for n in s["needs"]:
            if n not in skills:
                fail(f"{s['id']} needs {n}, which isn't in skills.yml")
            if skills[n]["topic"] == s["topic"] and skills[n]["index"] > s["index"]:
                warn(f"{s['id']} needs {n}, which comes after it on the {s['topic']} line")
    return topics, skills


def layout(topics, skills):
    by_id = {t["id"]: t for t in topics}
    attach = {}    # topic id -> station its line branches from (None for the start line)
    for t in topics:
        first = skills[t["skills"][0]["id"]]
        if not first["needs"]:
            attach[t["id"]] = None
        else:
            a = first["needs"][0]
            if skills[a]["topic"] == t["id"]:
                fail(f"{first['id']} is the first station of {t['id']}, so its first need must be on another line")
            attach[t["id"]] = a
    roots = [t for t, a in attach.items() if a is None]
    if len(roots) != 1:
        fail(f"exactly one line must start from a skill with no needs (found: {', '.join(roots) or 'none'})")

    # Columns: the start line from 0; a branch line starts one column right of its branch station.
    col, placed, pending = {}, set(), [t["id"] for t in topics]
    while pending:
        progress = False
        for t in list(pending):
            a = attach[t]
            if a is not None and a not in col:
                continue
            c0 = 0 if a is None else col[a] + 1
            for i, s in enumerate(by_id[t]["skills"]):
                col[s["id"]] = c0 + i
            pending.remove(t)
            progress = True
        if not progress:
            fail(f"these lines never connect back to the start: {', '.join(pending)}")

    # Rows: depth-first; a line's branches, rightmost branch station first.
    order = [t["id"] for t in topics]
    branches = {t: [] for t in order}
    for t in order:
        if attach[t] is not None:
            branches[skills[attach[t]]["topic"]].append(t)
    rows, offset = [], {}

    def place(t):
        rows.append(t)
        kids = sorted(branches[t], key=lambda k: (-col[attach[k]], order.index(k)))
        for k in kids:
            same = [s for s in kids if attach[s] == attach[k]]
            offset[k] = (len(same) - 1 - same.index(k)) * OFFSET   # nearest row gets the outermost drop
            place(k)

    place(roots[0])
    row = {t: i for i, t in enumerate(rows)}
    xy = {sid: (LEFT + col[sid] * COL, TOP + row[skills[sid]["topic"]] * ROW) for sid in skills}

    lines = []
    for t in topics:
        ids = [s["id"] for s in t["skills"]]
        x0, y = xy[ids[0]]
        xl = xy[ids[-1]][0]
        a = attach[t["id"]]
        if a is None:
            d = f"M{x0},{y} H{xl}"
        else:
            xa, ya = xy[a]
            xo = xa + offset[t["id"]]
            d = f"M{xo},{ya} V{y - DIAG} L{xo + DIAG},{y} H{xl}"
            # Self-check: the drop must not pass through another station.
            for sid, (sx, sy) in xy.items():
                if sid != a and abs(sx - xo) < 12 and ya < sy < y:
                    warn(f"the {t['id']} line runs through {sid}")
        lines.append({"topic": t["id"], "title": t["title"], "color": t.get("color", "#4a4a48"), "d": d})

    # A station's route: every station you pass riding from the start to it.
    prev = {}
    for t in topics:
        for i, s in enumerate(t["skills"]):
            prev[s["id"]] = t["skills"][i - 1]["id"] if i else attach[t["id"]]

    def route(sid):
        seen = set()
        while prev[sid] is not None:
            sid = prev[sid]
            seen.add(sid)
        return seen

    stations = []
    for t in topics:
        for s in t["skills"]:
            sk = skills[s["id"]]
            st = {"id": sk["id"], "topic": t["id"], "x": xy[sk["id"]][0], "y": xy[sk["id"]][1],
                  "label": wrap(sk["title"])}
            on_route = route(sk["id"])
            also = [n for n in sk["needs"] if n not in on_route]
            if also:
                st["also"] = also
            if sk.get("workshop"):
                st["workshop"] = True
            if prev[sk["id"]] is None:
                st["start"] = True
            stations.append(st)

    width = LEFT + max(col.values()) * COL + RIGHT
    height = TOP + (len(rows) - 1) * ROW + BOTTOM
    return {"width": width, "height": height, "lines": lines, "stations": stations}


def block(metro):
    out = [BLOCK_START, BLOCK_NOTE, "metro:", f"  width: {metro['width']}", f"  height: {metro['height']}", "  lines:"]
    out += [f"    - {json.dumps(l, ensure_ascii=False)}" for l in metro["lines"]]
    out.append("  stations:")
    out += [f"    - {json.dumps(s, ensure_ascii=False)}" for s in metro["stations"]]
    out.append(BLOCK_END)
    return "\n".join(out) + "\n"


def write(tree, metro):
    page = tree / "index.md"
    text = page.read_text()
    m = FRONT_MATTER.match(text)
    if not m:
        fail(f"{page} has no front matter")
    fm = m.group(1)
    new = block(metro)
    if BLOCK_START in fm:
        fm = re.sub(re.escape(BLOCK_START) + r".*?" + re.escape(BLOCK_END) + r"\n", lambda _: new, fm, flags=re.S)
    else:
        fm = fm + "\n" + new
    yaml.safe_load(fm)   # make sure the result still parses
    page.write_text(f"---\n{fm}---\n" + text[m.end():])


def svg(metro):
    """The map as a standalone SVG (for slides and print): styles inline, no
    links or done toggles, light theme, with the legend underneath."""
    bg, text, red = "#f8f7f3", "#1e1e1e", "#c8102e"
    sans = "'IBM Plex Sans', 'Helvetica Neue', Helvetica, Arial, sans-serif"
    mono = "'IBM Plex Mono', 'Courier New', monospace"

    # Legend: one row of items, wrapped to the map width.
    items = [(l["color"], l["title"]) for l in metro["lines"]] + [(None, "Workshop skill")]
    legend, x, y = [], LEFT - 60, metro["height"] + 10
    for color, title in items:
        w = 32 + len(title) * 7.2 + 28
        if x + w > metro["width"] - 20 and x > LEFT - 60:
            x, y = LEFT - 60, y + 26
        if color:
            legend.append(f'<rect x="{x}" y="{y - 5}" width="22" height="6" rx="3" fill="{color}"/>')
        else:
            legend.append(f'<circle cx="{x + 11}" cy="{y - 2}" r="6" fill="none" stroke="{red}" stroke-width="2.5"/>')
        legend.append(f'<text x="{x + 32}" y="{y + 2}" font-family="{mono}" font-size="13" fill="{text}">{escape(title)}</text>')
        x += w
    height = y + 24

    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {metro["width"]} {height}" '
           f'width="{metro["width"]}" height="{height}">',
           f'<rect width="100%" height="100%" fill="{bg}"/>']
    # Each line gets a casing in the background color, so crossings show a gap.
    for l in metro["lines"]:
        out.append(f'<path d="{l["d"]}" fill="none" stroke="{bg}" stroke-width="13" stroke-linecap="round" stroke-linejoin="round"/>')
        out.append(f'<path d="{l["d"]}" fill="none" stroke="{l["color"]}" stroke-width="7" stroke-linecap="round" stroke-linejoin="round"/>')
    color = {l["topic"]: l["color"] for l in metro["lines"]}
    for st in metro["stations"]:
        x, y, start = st["x"], st["y"], st.get("start")
        r = 11 if start else 8
        size, weight = ("12.5", ' font-weight="600"') if start else ("11.5", "")
        spans = "".join(f'<tspan x="{x}" y="{y - r - 8 - (len(st["label"]) - 1 - i) * 13}">{escape(line)}</tspan>'
                        for i, line in enumerate(st["label"]))
        out.append(f'<text text-anchor="middle" font-family="{sans}" font-size="{size}"{weight} fill="{text}">{spans}</text>')
        if start:
            out.append(f'<text x="{x - r - 10}" y="{y + 4}" text-anchor="end" font-family="{mono}" font-size="12" '
                       f'font-weight="600" letter-spacing="0.96" fill="{red}">START HERE</text>')
        if st.get("workshop"):
            out.append(f'<circle cx="{x}" cy="{y}" r="{r + 5}" fill="none" stroke="{red}" stroke-width="2.5"/>')
        out.append(f'<circle cx="{x}" cy="{y}" r="{r}" fill="{bg}" stroke="{color[st["topic"]]}" stroke-width="3.5"/>')
    out += legend
    out.append("</svg>")
    return "\n".join(out) + "\n"


def png(svg_path, png_path, width):
    """Render the SVG to PNG with Inkscape; skipped (with a warning) if it isn't installed."""
    if not shutil.which("inkscape"):
        warn(f"inkscape not found, so {png_path} wasn't updated")
        return False
    result = subprocess.run(["inkscape", str(svg_path), "--export-type=png", f"--export-width={width}",
                             f"--export-filename={png_path}"], capture_output=True, text=True)
    if result.returncode or not png_path.exists():
        warn(f"inkscape couldn't write {png_path}: {result.stderr.strip()}")
        return False
    return True


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("tree", type=Path, help="folder holding skills.yml and index.md")
    args = ap.parse_args()
    topics, skills = load(args.tree)
    metro = layout(topics, skills)
    write(args.tree, metro)
    svg_path, png_path = args.tree / "metro-map.svg", args.tree / "metro-map.png"
    svg_path.write_text(svg(metro))
    wrote = [args.tree / "index.md", svg_path]
    if png(svg_path, png_path, metro["width"] * PNG_SCALE):
        wrote.append(png_path)
    print(f"{len(skills)} stations on {len(metro['lines'])} lines; "
          f"map is {metro['width']}×{metro['height']} px. Wrote {', '.join(map(str, wrote))}")


if __name__ == "__main__":
    main()
